router.post('/', authorize('ADD'), validate(employeeSchema), async (req: AuthRequest, res) => {
  try {
    const { employeeCode, firstName, lastName, email, phone, gender, locationId, floorId, departmentId, sectionId, shiftId, designation, role, joiningDate } = req.body;
    
    // Resolve locationId (accepts cuid or code like BEL, DAV, SHI, or canonical aliases)
    let resolvedLocationId = locationId;
    const foundLoc = await prisma.location.findFirst({
      where: {
        OR: [
          { id: locationId },
          { code: locationId },
          ...(locationId === 'loc_bel' ? [{ code: 'BEL' }] : []),
          ...(locationId === 'loc_dav' ? [{ code: 'DAV' }] : []),
          ...(locationId === 'loc_shi' ? [{ code: 'SHI' }] : []),
        ],
      },
    });
    if (foundLoc) {
      resolvedLocationId = foundLoc.id;
    }

    const isMutationElevated = ['SUPER_ADMIN', 'ADMIN'].includes(req.user!.role);
    if (!isMutationElevated && resolvedLocationId !== req.user!.locationId) {
      return res.status(403).json({ error: 'Access denied' });
    }

    // Resolve optional departmentId if provided and not empty
    let resolvedDepartmentId: string | null = null;
    if (departmentId && String(departmentId).trim() !== '') {
      const foundDept = await prisma.department.findFirst({
        where: {
          OR: [
            { id: String(departmentId).trim() },
            { code: String(departmentId).trim() },
          ],
        },
      });
      if (foundDept) {
        resolvedDepartmentId = foundDept.id;
      }
    }

    // Check email uniqueness across users and employees
    const trimmedEmail = email ? String(email).trim().toLowerCase() : null;
    if (trimmedEmail) {
      const existingUserEmail = await prisma.user.findUnique({ where: { email: trimmedEmail } });
      const existingEmpEmail = await prisma.employee.findFirst({ where: { email: trimmedEmail } });
      if (existingUserEmail || existingEmpEmail) {
        return res.status(400).json({ error: 'This email is already registered' });
      }
    }

    // Check mobile number uniqueness across employees
    const trimmedPhone = phone ? String(phone).replace(/\D/g, '').slice(-10) : null;
    if (trimmedPhone && trimmedPhone.length === 10) {
      const existingEmpPhone = await prisma.employee.findFirst({
        where: {
          phone: {
            contains: trimmedPhone,
          },
        },
      });
      if (existingEmpPhone) {
        return res.status(400).json({ error: 'This mobile number is already registered' });
      }
    }

    // Employee number is supplied by HR (validated digits-only by the schema).
    // It is never auto-generated: a missing/invalid store number is an error,
    // not a licence to invent a placeholder identifier.
    const finalCode = String(employeeCode).trim();
    const codeCheck = validateEmployeeCode(finalCode);
    if (!codeCheck.ok) {
      return res.status(400).json({ error: codeCheck.error, field: 'employeeCode' });
    }
    const existing = await prisma.employee.findFirst({
      where: { employeeCode: finalCode },
    });
    if (existing) {
      return res.status(409).json({
        error: `Employee number ${finalCode} already exists (${existing.fullName}). Employee numbers must be unique.`,
        field: 'employeeCode',
      });
    }
    
    const fullName = `${String(firstName).trim()} ${String(lastName).trim()}`;
    
    const employee = await prisma.employee.create({
      data: {
        employeeCode: finalCode,
        firstName: String(firstName).trim(),
        lastName: String(lastName).trim(),
        fullName,
        email: trimmedEmail,
        phone: trimmedPhone || (phone ? String(phone).trim() : null),
        gender: gender || 'male',
        locationId: resolvedLocationId,
        floorId: floorId || null,
        departmentId: resolvedDepartmentId,
        sectionId: sectionId || null,
        shiftId: shiftId || null,
        designation: designation || 'Sales Consultant',
        role: role || 'SALES_EMPLOYEE',
        joiningDate: joiningDate ? new Date(joiningDate) : new Date(),
        status: 'ACTIVE',
      },
    });
    
    // Automatically create employee directory in uploads
    UserUploadService.ensureUserFolder(fullName, finalCode);

    // Generate QR codes
    const empQR = await prisma.qRCode.create({
      data: {
        token: `EMP-${finalCode}-${Date.now()}`,
        type: 'EMPLOYEE',
        employeeId: employee.id,
        locationId: resolvedLocationId,
        validFrom: new Date(),
        validTo: new Date(Date.now() + 365 * 24 * 60 * 60 * 1000),
      },
    });
    
    const dailyQR = await prisma.qRCode.create({
      data: {
        token: `DAILY-${finalCode}-${new Date().toISOString().split('T')[0].replace(/-/g, '')}`,
        type: 'DAILY',
        employeeId: employee.id,
        locationId: resolvedLocationId,
        validFrom: new Date(new Date().setHours(0, 0, 0, 0)),
        validTo: new Date(new Date().setHours(23, 59, 59, 999)),
      },
    });
    
    await prisma.employee.update({
      where: { id: employee.id },
      data: { qrCodeId: empQR.id, dailyQRCodeId: dailyQR.id },
    });
    
    // Create user account if email provided
    if (trimmedEmail) {
      const passwordHash = await PasswordService.hashPassword('password123');
      
      await prisma.user.create({
        data: {
          email: trimmedEmail,
          passwordHash,
          fullName,
          role: role || 'EMPLOYEE',
          permissions: ['VIEW'],
          employeeId: employee.id,
          locationId: resolvedLocationId,
        },
      });
    }

    // Publish notification for new employee creation
    await container.notificationService.publishEvent({
      eventId: 'EMP.CREATED',
      title: 'New Employee Created',
      message: `New employee ${fullName} (${finalCode}) has been added to ${resolvedLocationId}.`,
      type: 'INFO',
      severity: 'MEDIUM',
      entityType: 'employee',
      entityId: employee.id,
      locationId: resolvedLocationId,
      actionUrl: `/employees/profile/${employee.id}`,
      correlationId: `emp_created_${employee.id}`,
      metadata: { employeeCode: finalCode, fullName, locationId: resolvedLocationId, departmentId: resolvedDepartmentId, role: role || 'EMPLOYEE' },
    });

    res.status(201).json(employee);
  } catch (error: any) {
    console.error('Create employee error:', error);
    res.status(500).json({ error: error?.message || 'Failed to create employee' });
  }
});

router.put('/:id', authorize('EDIT'), validate(employeeSchema), async (req: AuthRequest, res) => {
  try {
    const { firstName, lastName, email, phone, gender, floorId, departmentId, sectionId, shiftId, designation, role, status, exitDate } = req.body;
    
    const existing = await prisma.employee.findUnique({ where: { id: req.params.id } });
    if (!existing) {
      return res.status(404).json({ error: 'Employee not found' });
    }
    
    const isEditElevated = ['SUPER_ADMIN', 'ADMIN'].includes(req.user!.role);
    if (!isEditElevated && existing.locationId !== req.user!.locationId) {
      return res.status(403).json({ error: 'Access denied' });
    }
    
    const fullName = `${firstName} ${lastName}`;
    
    const employee = await prisma.employee.update({
      where: { id: req.params.id },
      data: {
        firstName,
        lastName,
        fullName,
        email,
        phone,
        gender,
        floorId,
        departmentId,
        sectionId,
        shiftId,
        designation,
        role,
        status,
        exitDate: exitDate ? new Date(exitDate) : null,
      },
    });

    // Publish notification for employee profile update
    const changes: string[] = [];
    if (existing.firstName !== firstName || existing.lastName !== lastName) changes.push('name');
    if (existing.email !== email) changes.push('email');
    if (existing.phone !== phone) changes.push('phone');
    if (existing.floorId !== floorId) changes.push('floor');
    if (existing.departmentId !== departmentId) changes.push('department');
    if (existing.sectionId !== sectionId) changes.push('section');
    if (existing.shiftId !== shiftId) changes.push('shift');
    if (existing.designation !== designation) changes.push('designation');
    if (existing.role !== role) changes.push('role');
    if (existing.status !== status) changes.push('status');

    if (changes.length > 0) {
      await container.notificationService.publishEvent({
        eventId: changes.includes('status') ? 'EMP.STATUS_CHANGED' : 
               changes.some(c => ['department', 'floor', 'section'].includes(c)) ? 'EMP.DEPT_CHANGED' : 'EMP.PROFILE_UPDATED',
        title: changes.includes('status') ? 'Employee Status Changed' : 
               changes.some(c => ['department', 'floor', 'section'].includes(c)) ? 'Employee Department/Location Changed' : 'Employee Profile Updated',
        message: `Employee ${fullName} (${existing.employeeCode}) profile updated. Changed fields: ${changes.join(', ')}.`,
        type: changes.includes('status') ? 'CRITICAL' : 'INFO',
        severity: changes.includes('status') ? 'CRITICAL' : 'MEDIUM',
        entityType: 'employee',
        entityId: employee.id,
        locationId: existing.locationId,
        actionUrl: `/employees/profile/${employee.id}`,
        correlationId: `emp_updated_${employee.id}_${Date.now()}`,
        metadata: { changes, previousValues: { floorId: existing.floorId, departmentId: existing.departmentId, status: existing.status } },
      });
    }

    res.json(employee);
  } catch (error) {
    console.error('Update employee error:', error);
    res.status(500).json({ error: 'Failed to update employee' });
  }
});

